# Links khensu-core's UniFFI build into KhensuKit:
#   ../khensu-core/target/KhensuCore.xcframework -> Packages/KhensuKit/Frameworks/ (symlink)
#   ../khensu-core/target/swift/KhensuCore.swift -> Packages/KhensuKit/Sources/KhensuCoreBindings/
# Both are gitignored. With them present, KhensuKit builds RustCore; without
# them (or after `scripts/link-core.sh --unlink`) it builds MockCore only.
#
# Build the framework first in khensu-core: scripts/build-xcframework.sh
set -euo pipefail
cd "$(dirname "$0")/.."

CORE=${KHENSU_CORE:-../khensu-core}
KIT=Packages/KhensuKit
FW=$KIT/Frameworks/KhensuCore.xcframework
BINDINGS=$KIT/Sources/KhensuCoreBindings/KhensuCore.swift

if [[ "${1:-}" == "--unlink" ]]; then
  rm -f "$FW" "$BINDINGS"
  echo "unlinked khensu-core; KhensuKit builds MockCore only"
  exit 0
fi

[[ -d "$CORE/target/KhensuCore.xcframework" ]] || { echo "missing $CORE/target/KhensuCore.xcframework (run khensu-core/scripts/build-xcframework.sh)"; exit 1; }
[[ -f "$CORE/target/swift/KhensuCore.swift" ]] || { echo "missing $CORE/target/swift/KhensuCore.swift"; exit 1; }

mkdir -p "$KIT/Frameworks" "$(dirname "$BINDINGS")"
ln -sfn "$(cd "$CORE/target" && pwd)/KhensuCore.xcframework" "$FW"
{
  echo "// Generated by UniFFI in khensu-core (Apache-2.0); copied by scripts/link-core.sh. Do not edit."
  cat "$CORE/target/swift/KhensuCore.swift"
} > "$BINDINGS"
echo "linked $(git -C "$CORE" rev-parse --short HEAD 2>/dev/null || echo khensu-core) into $KIT"
